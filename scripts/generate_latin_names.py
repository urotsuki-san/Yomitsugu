"""Generate the packed name table from Simple Icons 16.38.0 metadata."""
import argparse
import hashlib
import json
import re
from pathlib import Path

SOURCE_SHA256 = "833fe5a31295929aaac80a4477e20b1df048284da93ef281f551ed6d9ad7958f"
SUPPLEMENT = (
    "amazon microsoft windows office outlook excel powerpoint onedrive linkedin azure "
    "openai chatgpt nintendo playstation adobe photoshop acrobat googlemaps googlechrome "
    "googlecloud rakuten mercari androidstudio"
).split()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("metadata", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    data = args.metadata.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        parser.error("expected data/simple-icons.json from Simple Icons 16.38.0")
    names = set(SUPPLEMENT)
    for entry in json.loads(data):
        for word in (entry["title"], *entry.get("aliases", {}).get("aka", [])):
            if re.fullmatch(r"[A-Za-z][A-Za-z0-9]{2,39}", word):
                names.add(word.lower())

    ordered = sorted(names)
    offsets = []
    size = 0
    for word in ordered:
        offsets.append(size)
        size += len(word) + 1
    if size >= 65535:
        raise ValueError("name table exceeds uint16_t offsets")

    lines = [
        "// Generated by scripts/generate_latin_names.py using Simple Icons 16.38.0 (CC0).",
        "// Input SHA-256 " + SOURCE_SHA256,
        "static constexpr char kLatinNameBytes[] =",
    ]
    for i in range(0, len(ordered), 10):
        lines.append('    "' + ''.join(x + r'\0' for x in ordered[i:i+10]) + '"')
    lines += [
        ";",
        f"static constexpr size_t kLongestLatinName = {max(map(len, ordered))};",
        "static constexpr uint16_t kLatinNameOffsets[] = {",
    ]
    for i in range(0, len(offsets), 18):
        lines.append('    ' + ','.join(map(str, offsets[i:i+18])) + ',')
    args.output.write_text('\n'.join([*lines, "};", ""]), encoding="ascii")
    print(f"{len(ordered)} entries, {size + 1 + 2 * len(ordered)} bytes")


if __name__ == "__main__":
    main()
