"""Build the read-only group index for the bundled public_dictionary.tsv."""
from __future__ import annotations

import argparse
import hashlib
import io
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUCKETS = 1 << 15
OFFSET_BITS = 25
PRESENT, SYMBOL_ONLY, SUPPLEMENTAL, PRIORITY, ENGLISH = 1, 2, 4, 8, 16


def hash_key(key: bytes) -> int:
    value = 2166136261
    for byte in key:
        value = ((value ^ byte) * 16777619) & 0xFFFFFFFF
    return value


def kind(key: bytes, word: bytes, pos: str) -> int:
    if pos == "補助語":
        return SUPPLEMENTAL
    if pos in {"名詞", "noun"}:
        return PRIORITY
    if pos in {"記号", "symbol"}:
        return SYMBOL_ONLY
    return ENGLISH if pos == "英単語" and key == word else 0


def generate(payload: bytes) -> str:
    if len(payload) > 1 << OFFSET_BITS:
        raise ValueError("Dictionary exceeds the 32 MiB limit")
    groups: list[list[tuple[int, int, int]]] = [[] for _ in range(BUCKETS)]
    previous = None
    words: set[bytes] = set()
    row_count = 0
    has_supplemental = False
    flags = PRESENT | SYMBOL_ONLY
    start = 0
    prefix_max = [0] * 512

    def store_group() -> None:
        if previous is None:
            return
        if len(previous) >= 6:
            bucket = hash_key(previous[:6]) % len(prefix_max)
            prefix_max[bucket] = max(prefix_max[bucket], len(previous))
        hashed = hash_key(previous)
        groups[hashed & (BUCKETS - 1)].append((start, flags, hashed))

    offset = 0
    for raw in io.BytesIO(payload):
        line = raw.removesuffix(b"\n").removesuffix(b"\r")
        if not line or line.startswith((b"#", b"!")):
            if previous is not None:
                raise ValueError("Non-contiguous group data in bundled dictionary")
            offset += len(raw)
            continue
        if len(line) > 4096 or b"\0" in line:
            raise ValueError(f"Invalid dictionary row at byte {offset}")
        line.decode("utf-8")
        key, word, pos = line.split(b"\t")
        if not 0 < len(key) <= 512 or not 0 < len(word) <= 1024:
            raise ValueError(f"Invalid reading or surface at byte {offset}")
        if key != previous:
            if previous is not None and key < previous:
                raise ValueError("Bundled readings must be sorted")
            store_group()
            start, previous, words, flags = offset, key, set(), PRESENT | SYMBOL_ONLY
        # The source-tree dictionary generator emits unique reading/word pairs.
        # A modified dictionary is validated and deduplicated by PublicIndex::Build.
        if word in words or len(words) >= 32:
            raise ValueError(f"Duplicate or too many surfaces for reading at byte {offset}")
        words.add(word)
        flag = kind(key, word, pos.decode("utf-8"))
        if flag != SYMBOL_ONLY:
            flags &= ~SYMBOL_ONLY
        flags |= flag & ~SYMBOL_ONLY
        has_supplemental |= flag == SUPPLEMENTAL
        row_count += 1
        offset += len(raw)
    store_group()
    if not row_count or row_count > 700000:
        raise ValueError("Invalid bundled row count")
    # Encode only flags that occur in this dictionary. Use every remaining
    # bit as a fingerprint, then check the original bytes on a match.
    flag_values = sorted({flag for group in groups for _, flag, _ in group})
    offset_bits = (len(payload) - 1).bit_length()
    flag_bits = (len(flag_values) - 1).bit_length()
    fingerprint = 0xffffffff ^ ((1 << (offset_bits + flag_bits)) - 1)
    entries = []
    starts = []
    for group in groups:
        # The engine's 700,000-row cap leaves the top twelve bits of each
        # bucket offset free for a membership filter.
        bloom = 0
        starts.append(len(entries))
        for offset, flag, hashed in group:
            bloom |= 1 << ((hashed >> 15) % 12)
            entries.append(offset | (flag_values.index(flag) << offset_bits) | (hashed & fingerprint))
        starts[-1] |= bloom << 20
    starts.append(len(entries))

    def array(name: str, values: list[int], fmt: str, element: str = "std::uint32_t") -> str:
        lines = [", ".join(format(n, fmt) for n in values[i:i+10]) for i in range(0, len(values), 10)]
        return "inline constexpr "+element+" "+name+"[] = {\n    "+",\n    ".join(lines)+"\n};\n"

    digest = hashlib.sha256(payload).digest()
    return (
        "// Generated by scripts/generate_bundled_index.py from native/assets/public_dictionary.tsv.\n"
        "#pragma once\n#include <cstdint>\nnamespace ime::bundled_dictionary {\n"
        f"inline constexpr std::uint32_t file_size = {len(payload)};\n"
        f"inline constexpr std::uint32_t row_count = {row_count};\n"
        f"inline constexpr bool has_supplemental = {str(has_supplemental).lower()};\n"
        "inline constexpr unsigned char sha256[] = {"+", ".join(hex(b) for b in digest)+"};\n"
        + f"inline constexpr unsigned offset_bits = {offset_bits};\n"
        + f"inline constexpr std::uint32_t flag_mask = {(1 << flag_bits) - 1}u;\n"
        + f"inline constexpr std::uint32_t fingerprint_mask = {fingerprint:#010x}u;\n"
        + array("prefix_max", prefix_max, "d", "std::uint16_t")
        + array("flag_values", flag_values, "d") + array("bucket_starts", starts, "#010x") + array("groups", entries, "#010x") + "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    dictionary = ROOT / "native/assets/public_dictionary.tsv"
    header = ROOT / "native/src/bundled_public_index.h"
    contents = generate(dictionary.read_bytes()).encode("utf-8")
    if args.check:
        if not header.is_file() or header.read_bytes().replace(b"\r\n", b"\n") != contents:
            raise SystemExit("Bundled dictionary index is stale")
    else:
        header.write_bytes(contents)


if __name__ == "__main__":
    main()
